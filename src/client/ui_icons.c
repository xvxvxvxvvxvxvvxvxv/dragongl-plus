/*Rasterise every icon into dst (RGBA8, stride in pixels) at the given
 * cell size (multiple of 16), cells laid out left-to-right from (ox,oy).*/
void ui_icons_rasterize(uint8_t *dst, int stride, int ox, int oy, int cell, int per_row) {
    int k = cell / 16;
    for (int i = 1; i < ICON_COUNT; i++) {
        int cx = ox + (i % per_row) * cell, cy = oy + (i / per_row) * cell;
        for (int y = 0; y < 16; y++) {
            const char *row = ICONS[i][y];
            if (!row) continue;
            int len = (int)strlen(row);
            for (int x = 0; x < 16 && x < len; x++) {
                char ch = row[x];
                if (ch == '.') continue;
                uint8_t r = 255, g = 0, b = 255;
                for (size_t p = 0; p < sizeof(PAL) / sizeof(PAL[0]); p++)
                    if (PAL[p].key == ch) { r = PAL[p].r; g = PAL[p].g; b = PAL[p].b; break; }
                for (int yy = 0; yy < k; yy++)
                    for (int xx = 0; xx < k; xx++) {
                        uint8_t *px = dst + ((size_t)(cy + y * k + yy) * stride + (size_t)(cx + x * k + xx)) * 4;
                        px[0] = r; px[1] = g; px[2] = b; px[3] = 255;
                    }
            }
        }
    }
}
