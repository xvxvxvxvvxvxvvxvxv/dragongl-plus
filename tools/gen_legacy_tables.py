"""Name tables of the items and spells of DragonGL+ 2026.10.

The saves of the DragonGL+ server of October 2026 refer to items and
spells by their position in data/items.json and data/spells.json of that
release. src/server/legacy_import.c maps them to today's data by name:
this script writes those names, in order, to src/server/legacy_tables.c.

    tools/gen_legacy_tables.py <items.json> <spells.json> > src/server/legacy_tables.c

(the two files of DragonGL+ 2026.10, e.g. from git show <tag>:data/items.json)
"""
import json
import sys


def c_string(s):
    out = []
    for ch in s.strip():
        if ch in '\\"':
            out.append('\\' + ch)
        elif 32 <= ord(ch) < 127:
            out.append(ch)
        else:
            out.extend('\\%03o' % b for b in ch.encode('utf-8'))
    return '"' + ''.join(out) + '"'


def main():
    items = json.load(open(sys.argv[1], encoding='utf-8'))['items']
    spells = json.load(open(sys.argv[2], encoding='utf-8'))['spells']
    print('/* Generated by tools/gen_legacy_tables.py: do not edit. */')
    print('/* Items and spells of DragonGL+ 2026.10, in the order of its data files. */')
    print('#include "legacy_import.h"')
    print()
    print('const char *const LEGACY_ITEM_NAMES[] = {')
    for it in items:
        print('    %s,' % c_string(it.get('name') or ''))
    print('};')
    print('const int LEGACY_ITEM_COUNT = (int)(sizeof(LEGACY_ITEM_NAMES) / sizeof(LEGACY_ITEM_NAMES[0]));')
    print()
    print('const char *const LEGACY_SPELL_NAMES[] = {')
    for sp in spells:
        print('    %s,' % c_string(sp.get('name') or ''))
    print('};')
    print('const int LEGACY_SPELL_COUNT = (int)(sizeof(LEGACY_SPELL_NAMES) / sizeof(LEGACY_SPELL_NAMES[0]));')


if __name__ == '__main__':
    main()
